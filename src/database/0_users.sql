CREATE TABLE [01_users] (
    [id] INT IDENTITY(1,1) UNIQUE, 
    [createdDate] DATETIME DEFAULT GETDATE(),
    [updatedDate] DATETIME DEFAULT GETDATE(),
    [code] NVARCHAR(50) PRIMARY KEY,

    [email] NVARCHAR(150) NOT NULL UNIQUE,
    [name] NVARCHAR(150) NOT NULL,
    [province] NVARCHAR(75) NOT NULL,
    [nExplotations] INT NOT NULL DEFAULT 0,

    [blockedDate] DATETIME NULL,
    [blockedReason] NVARCHAR(1000) NULL,

    [dppSigned] BIT NOT NULL DEFAULT 0,
    [dppSignedDate] DATETIME NULL
);

    -- Column MS_descriptions. Only in main table.
        -- Describes the type of widget/value generation method
        /*
            {
            auto: generated with python code based on other data
            hand: generated by hand. Any value is possible
            closed_selection_unique: manually (coded) controlled list for one single selection
            closed_selection_multiple: manually (coded) controlled list for multiple selection
            open_selection_unique: list of unique values from the column in DB + "new" option
            open_selection_multiple: list of unique values from the column in DB + option to add multiple new values
            numeric_string: in database, dtype is VARCHAR (string) but user is forced to write INT/DECIMAL in GUI
            }
        */
